    out.append("</div></div></section>")
    # steps (sand)
    out.append('<section class="page-section page-section--sand section--sand-s">')
    out.append(eyebrow_split(c(p + ".steps_head.eyebrow"), f'<h2 class="page-h2">{c(p + ".steps_head.h2")}</h2>', "page-split--steps"))
    out.append('<ol class="page-steps">')
