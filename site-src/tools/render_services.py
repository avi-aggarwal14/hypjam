def grid_card(spec: str, toks: list[dict], width: int | None) -> str:
    s = spec.lower()
    titles = [t for t in toks if t["kind"] == "title"]
    m = re.search(r"(\d)×(\d) grid", spec)
    rows_n, cols_n = (int(m.group(1)), int(m.group(2))) if m else (2, 3)
    out = [card_open(titles[0]["text"] if titles else None, None, "", width)]
    rowlabels, collabels, cells = [], [], []
    mode = "cells"
    for t in toks:
        if t["kind"] == "title":
            continue
        b = t["before"].lower()
        if "row labels" in b or (mode == "rows" and re.match(r"^\s*(,|and)\s*$", b[-6:])):
            mode = "rows"; rowlabels.append(t["text"]); continue
        if "column labels" in b or (mode == "cols" and re.match(r"^\s*(,|and)\s*$", b[-6:])):
            mode = "cols"; collabels.append(t["text"]); continue
        if t["kind"] == "footer":
            continue
        cells.append(t)
    if rowlabels and collabels:
        out.append(f'<div class="mock-grid mock-grid--labels" style="--cols:{len(collabels)}">')
        out.append('<span class="mock-tile mock-tile--head"></span>')
        for cl in collabels:
            out.append(f'<span class="mock-tile mock-tile--head">{esc(cl)}</span>')
        filled = [t for t in cells if "filled" in t["before"].lower() or "shot" in t["text"].lower()]
        label = filled[0]["text"] if filled else "shot"
        k = 0
        total = len(rowlabels) * len(collabels)
        nfill = 6 if total == 9 else total - 2
        jam_at = 4
        for r, rl in enumerate(rowlabels):
            out.append(f'<span class="mock-tile mock-tile--rowhead">{esc(rl)}</span>')
            for cc in range(len(collabels)):
                idx = r * len(collabels) + cc
                if idx < nfill or (idx == total - 1 and nfill >= total):
                    dot = '<span class="mock-dot mock-dot--jam" aria-hidden="true"></span>' if idx == jam_at else ""
                    out.append(f'<span class="mock-tile" style="--i:{k}">{esc(label)}{dot}</span>')
                else:
                    out.append(f'<span class="mock-tile mock-tile--empty" style="--i:{k}"></span>')
                k += 1
        out.append("</div>")
    else:
        tiles = [t for t in cells if t["kind"] in ("row", "chip", "label")]
        out.append(f'<div class="mock-grid" style="--cols:{cols_n}">')
        jam_idx = {1, 4} if "jam dot" in s else set()
        for k, t in enumerate(tiles[: rows_n * cols_n]):
            dot = '<span class="mock-dot mock-dot--jam" aria-hidden="true"></span>' if k in jam_idx else ""
            sub = '<span class="mock-tile__s"><span class="mock-line mock-line--w80" style="display:block;height:5px"></span></span>' if "example" in s else ""
            out.append(f'<span class="mock-tile" style="--i:{k}">{esc(t["text"])}{dot}{sub}</span>')
        out.append("</div>")
    out.append(card_close([t for t in toks if t["kind"] == "footer"]))
    return "".join(out)


