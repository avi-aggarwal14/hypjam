def _bubble(x, y, w, h, tail="bl", lines=2, dotted=False):
    r = 10
    p = [f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}"/>']
    if tail == "bl":
        p.append(f'<path d="M{x + 18} {y + h}v14l14-14"/>')
    else:
        p.append(f'<path d="M{x + w - 32} {y + h}v14l-14-14"/>')
    if dotted:
        p.append(f'<path d="M{x + 18} {y + h / 2}h{w - 36}" stroke-dasharray="3 5"/>')
    else:
        for i in range(lines):
            p.append(f'<path d="M{x + 18} {y + 18 + i * 12}h{w - 36 - i * 22}"/>')
    return "".join(p)


def _doc(x, y, w, h, lines=3, fold=True):
    p = []
    if fold:
        p.append(f'<path d="M{x} {y}h{w - 18}l18 18v{h - 18}H{x}z"/><path d="M{x + w - 18} {y}v18h18"/>')
    else:
        p.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6"/>')
    for i in range(lines):
        p.append(f'<path d="M{x + 16} {y + 30 + i * 14}h{w - 32 - (i % 2) * 16}"/>')
    return "".join(p)


