def card_open(title: str | None, right: str | None = None, cls: str = "", width: int | None = None, rec: bool = False) -> str:
    style = f' style="--w:{min(width, 560)}px"' if width else ""
    head = ""
    if title or right:
        r = ""
        if right:
            r = f'<span class="mock-head__r">{esc(right)}</span>'
        elif rec:
            r = '<span class="mock-head__r"><span class="mock-dot mock-dot--jam"></span>REC</span>'
        head = f'<div class="mock-head"><span class="mock-head__t">{esc(title or "")}</span>{r}</div>'
    return f'<div class="mock-card{(" " + cls) if cls else ""}"{style}>{head}'


def card_close(footer_toks: list[dict], extra_foot: str = "") -> str:
    foot = ""
    if footer_toks or extra_foot:
        inner = "".join(chip(t["text"]) if "chip" in t["before"].lower()[-14:] else f'<span>{esc(t["text"])}</span>'
                        for t in footer_toks)
        foot = f'<div class="mock-foot">{inner}{extra_foot}</div>'
    return f"{foot}</div>"


def chips_row(toks: list[dict], default_jam_first: bool = False) -> str:
    if not toks:
        return ""
    out = []
    for k, t in enumerate(toks):
        cls = "mock-chip--jam" if ("jam" in t["marks"] or "current" in t["marks"]) else ""
        if "ink" in t["marks"]:
            cls = "mock-chip--ink"
        if "tick" in t["marks"]:
            out.append(f'<span class="mock-chip {cls}">{tick()}{esc(t["text"])}</span>')
        else:
            out.append(chip(t["text"], cls))
    return f'<div class="mock-chips">{"".join(out)}</div>'


def phone_html(spec: str, lg: bool, tc_seed: int, toks: list[dict]) -> str:
    s = spec.lower()
    inner = ['<span class="mock-phone__rec">REC</span>']
    m = re.search(r"(\d{2}):(\d{2}):(\d{2})", spec)
    seed = tc_seed
    if m:
        seed = int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3))
    inner.append(f'<span class="mock-phone__tc" data-tc="{seed}">{seed // 3600:02d}:{(seed // 60) % 60:02d}:{seed % 60:02d}</span>')
    if "figure" in s:
        inner.append('<span class="mock-phone__figure" aria-hidden="true"><svg viewBox="0 0 100 120" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round">'
                     '<circle cx="50" cy="30" r="13"/><path d="M28 78c2-18 10-26 22-26s20 8 22 26"/><path d="M14 92h72M22 92v22M78 92v22"/>'
                     '<rect x="56" y="70" width="16" height="22" rx="2"/></svg></span>')
    if "level meter" in s or "meter" in s:
        inner.append('<span class="mock-phone__meter" aria-hidden="true"><i></i><i></i><i></i><i></i><i></i><i></i><i></i><i></i></span>')
    bub = [t for t in toks if t["kind"] == "bubble"]
    if bub:
        inner.append(f'<span class="mock-call">{esc(bub[0]["text"])}</span>')
    return f'<div class="mock-phone{" mock-phone--lg" if lg else ""}" aria-hidden="true">{"".join(inner)}</div>'


def list_card(spec: str, toks: list[dict], width: int | None, opts: dict, cls: str = "") -> str:
    """The workhorse: header · labels · rows · chips · footer."""
    titles = [t for t in toks if t["kind"] == "title"]
    title = titles[0]["text"] if titles else None
    right = titles[1]["text"] if len(titles) > 1 else None
    s = spec.lower()
    rec = "rec dot" in s and "phone" not in s
    out = [card_open(title, right, cls, width, rec=rec)]
    if "masked" in s and "code" in s:                       # a code field sits at the top of the card
        out.append('<div class="mock-code" aria-hidden="true"><span>' + "</span><span>".join(["\u2022" * 4] * 3) + "</span></div>")
    i = 0
    rows_open = False
    pending_chips: list[dict] = []
    body_toks = [t for t in toks if t["kind"] not in ("title", "footer", "bubble")]
    # explicit "N rows" with no quoted rows → skeleton rows
    quoted_rows = [t for t in body_toks if t["kind"] == "row"]
    n_stub = find_row_count(spec) if len(quoted_rows) <= 1 else 0
    marked = find_marked_rows(spec)
    # "(01 Problem, 02 Discovery, …)" — a numbered enumeration the spec writes in
    # parentheses instead of quotes. Real labels beat skeleton lines.
    enum = paren_enum(spec) if len(quoted_rows) <= 2 else []
    if enum:
        tags = extend_tags(paren_tag_list(spec), len(enum))
        out.append('<div class="mock-rows">')
        for k, (num, label) in enumerate(enum):
            tag = f'<span class="mock-row__v">{esc(tags[k])}</span>' if k < len(tags) else ""
            out.append(f'<div class="mock-row mock-row--stack" style="--i:{k}">'
                       f'<span class="mock-row__n">{esc(num)}</span>'
                       f'<span class="mock-row__t">{esc(label)}</span>{tag}'
                       f'<span class="mock-row__d"><span class="mock-line {["mock-line--w80","mock-line--w60","mock-line","mock-line--w45"][k % 4]}"></span></span></div>')
        out.append("</div>")
        i = len(enum)
        n_stub = 0
        drop = {t["text"] for t in quoted_rows} | set(tags)
        body_toks = [t for t in body_toks if t["text"] not in drop]
    chip_for_marked = None
    strike: dict = {}
    for t in body_toks:
        if t["kind"] == "chip" and re.search(r"(carry|gain|with) a jam tick and a\s*$", t["before"]):
            chip_for_marked = t["text"]
        if t["kind"] == "chip" and "strike" in t["marks"]:
            strike[len(strike) + 1] = t["text"]
    if n_stub and "grid" not in s:
        if "strikethrough" in s and quoted_rows:
            strike = {n_stub: quoted_rows[0]["text"]}
            quoted_rows = []
        out.append('<div class="mock-rows">')
        out.append(stub_rows(n_stub, marked, chip_for_marked, numbered=True, checkboxes="checkbox" in s, strike_rows=strike))
        out.append("</div>")
        i = n_stub
        body_toks = [t for t in body_toks if t["kind"] != "row" and t["text"] != chip_for_marked]
    for t in body_toks:
        if t["kind"] == "label":
            if pending_chips:
                out.append(chips_row(pending_chips)); pending_chips = []
            if rows_open:
                out.append("</div>"); rows_open = False
            out.append(f'<p class="mock-label">{esc(t["text"])}</p>')
        elif t["kind"] in ("row", "note"):
            if pending_chips:
                out.append(chips_row(pending_chips)); pending_chips = []
            if not rows_open:
                out.append('<div class="mock-rows">'); rows_open = True
            out.append(row_html(t, i, opts)); i += 1
        elif t["kind"] == "chip":
            if rows_open and not pending_chips:
                out.append("</div>"); rows_open = False
            pending_chips.append(t)
    if rows_open:
        out.append("</div>")
    if pending_chips:
        out.append(chips_row(pending_chips))
    if "signature line" in s:
        out.append('<div class="mock-sig"><span class="mock-sig__line" aria-hidden="true"></span><span class="mock-dot mock-dot--jam" aria-hidden="true"></span><span>signed</span></div>')
    if "stamp" in s:
        st = [t for t in toks if "stamp" in t["before"].lower()]
        if st:
            out.append(f'<span class="mock-stamp" aria-hidden="true">{esc(st[0]["text"])}</span>')
    footers = [t for t in toks if t["kind"] == "footer"]
    out.append(card_close(footers))
    return "".join(out)


