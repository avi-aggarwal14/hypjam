def quoted_spans(spec: str) -> list[tuple[str, int, int]]:
    """Single-quoted strings, tolerant of apostrophes inside them ('DON'T', 'creator's')."""
    out = []
    i, n = 0, len(spec)
    openers = " ([:→,;/—-"
    closers = " ,.;:)]/—-\n"
    while i < n:
        ch = spec[i]
        if ch == "'" and (i == 0 or spec[i - 1] in openers):
            j = i + 1
            while j < n:
                if spec[j] == "'" and (j + 1 == n or spec[j + 1] in closers):
                    break
                j += 1
            if j < n:
                out.append((spec[i + 1:j], i, j + 1))
                i = j + 1
                continue
        i += 1
    return out


WORDNUM = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10}


def wordnum(w: str) -> int:
    w = w.lower()
    return WORDNUM.get(w, int(w) if w.isdigit() else 0)


def classify(spec: str) -> list[dict]:
    """Every quoted string with a kind and the marks the spec hangs on it."""
    toks = []
    for text, s, e in quoted_spans(spec):
        before = spec[max(0, s - 34):s]
        after = spec[e:e + 160]   # long enough to see a following parenthetical
        kind = "row"
        if re.search(r"(titled|[Hh]eader(?: row)?|heading|[Hh]eader:)\s*$", before):
            kind = "title"
        elif re.search(r"[Ff]ooter(?: line| chip| in grey|:)?\s*:?\s*$", before):
            kind = "footer"
        elif re.search(r"(chip|chips|tag|pill|labelled|label|stamp(?: outline)?(?: top-right)?(?: reading)?|strip reads|reads)\s*$", before) \
                or re.search(r"^\s*(chip|tag|pill|timing tag)\b", after) \
                or re.search(r"^\s*(and|,)\s*'", after) and re.search(r"(chip|chips|tag|labelled)\b[^.]{0,40}$", before):
            kind = "chip"
        elif re.search(r"(call bubble|bubble reading|bubble)\s*$", before):
            kind = "bubble"
        elif re.search(r"(note under|note under row \d+|notes line under row \d+|note:|small note)\s*[^']{0,12}$", before):
            kind = "note"
        elif re.search(r"(a second small card|a narrow status card|note card)[^']{0,20}$", before):
            kind = "row"
        if kind in ("row", "chip") and text.isupper() and len(text) <= 28 and kind == "row" and "·" not in text \
                and not re.search(r"\d", text):
            kind = "label"
        marks = set()
        a = after.lower()
        if text.endswith(" ✓") or "✓" in text or re.match(r"^\s*\((tick|tick, jam)\)", a) or re.match(r"^\s*\(jam", a) \
                or re.match(r"^\s*with a jam tick", a) or re.match(r"^\s*\(?tick", a):
            marks.add("tick")
        if re.match(r"^\s*\(empty", a):
            marks.add("empty")
        if re.match(r"^\s*\((current|jam, current)", a) or re.match(r"^\s*\(jam, current", a) or "(current" in a[:12]:
            marks.add("current")
        if "strikethrough" in a[:30] or "struck" in a[:20] or "strikethrough" in before.lower()[-24:] \
                or "struck-through" in before.lower()[-30:]:
            marks.add("strike")
        if re.match(r"^\s*in jam", a) or re.match(r"^\s*\(jam", a) or re.match(r"^\s*chip in jam", a) \
                or re.search(r"jam (chip|outline|tick)?\s*'?$", before.lower()):
            marks.add("jam")
        if "★" in text:
            marks.add("star")
        if "filled black" in a[:40] or re.search(r"filled black[^']{0,30}$", before.lower()):
            marks.add("ink")
        toks.append({"text": text.replace(" ✓", "").replace("✓", "").replace(" · ★", "").replace("★", "").strip(),
                     "kind": kind, "marks": marks, "before": before, "after": after})
    return toks


def tick(jam: bool = True) -> str:
    return f'<span class="mock-tick{"" if jam else " mock-tick--ink"}" aria-hidden="true">{TICK_SVG}</span>'


def chip(text: str, cls: str = "") -> str:
    return f'<span class="mock-chip{(" " + cls) if cls else ""}">{esc(text)}</span>'


def split_parts(text: str) -> list[str]:
    return [p.strip() for p in re.split(r"\s+·\s+", text) if p.strip()]


def row_html(tok: dict, i: int, opts: dict) -> str:
    text, marks = tok["text"], tok["marks"]
    cls = ["mock-row"]
    if "strike" in marks:
        cls.append("mock-row--strike")
    if tok["kind"] == "note":
        cls.append("mock-row--muted")
    parts = split_parts(text)
    n_html = ""
    head = parts[0] if parts else text
    m = re.match(r"^(\d{2})\s+(.+)$", head)
    mt = re.match(r"^(\d{1,2}:\d{2})\s+(.+)$", head)
    if m:
        n_html = f'<span class="mock-row__n">{m.group(1)}</span>'
        head = m.group(2)
    elif mt:
        n_html = f'<span class="mock-row__n" style="width:36px">{mt.group(1)}</span>'
        head = mt.group(2)
    elif opts.get("numbered"):
        n_html = f'<span class="mock-row__n">{i + 1:02d}</span>'
    lead = ""
    if opts.get("avatars"):
        lead = '<span class="mock-avatar" aria-hidden="true"></span>'
    if opts.get("checkboxes"):
        lead = tick() if "tick" in marks else '<span class="mock-ring" aria-hidden="true"></span>'
    if opts.get("files"):
        lead = ('<svg width="12" height="14" viewBox="0 0 12 14" fill="none" stroke="currentColor" stroke-width="1" '
                'style="flex-shrink:0;color:#a9a8a3" aria-hidden="true"><path d="M1 1h7l3 3v9H1z M8 1v3h3"/></svg>')
    vals = parts[1:]
    tail = []
    for v in vals:
        if opts.get("val_chips"):
            vc = "mock-chip--jam" if ("jam" in marks or "current" in marks) else ""
            tail.append(chip(v, vc))
        else:
            tail.append(f'<span class="mock-row__v">{esc(v)}</span>')
    if "tick" in marks and not opts.get("checkboxes"):
        tail.append(tick())
    if "star" in marks:
        tail.append('<span class="mock-star" aria-hidden="true">★</span>')
    if "empty" in marks:
        tail.append('<span class="mock-ring" aria-hidden="true"></span>')
    if "current" in marks and "tick" not in marks and not opts.get("val_chips"):
        tail.append('<span class="mock-dot mock-dot--jam" aria-hidden="true"></span>')
    if opts.get("cross") and "tick" not in marks:
        tail.append('<span class="mock-x" aria-hidden="true">×</span>')
    if opts.get("toggles"):
        tail.append('<span class="mock-toggle mock-toggle--on" aria-hidden="true"></span>')
    # "'window' row with a small segmented bar (7 · 30 · 60 · 365) and the 60 segment filled"
    mseg = re.match(r"^\s*(?:date\s+)?rows?\b[^.]{0,40}segmented bar\s*\(([^)]*)\)", tok["after"])
    if mseg:
        segs = [x.strip() for x in re.split(r"[·,]", mseg.group(1)) if x.strip()]
        mfill = re.search(r"the (\S+) segment filled", tok["after"])
        fill = mfill.group(1) if mfill else (segs[-1] if segs else "")
        tail.append('<span class="mock-seg" aria-hidden="true">'
                    + "".join(f'<i class="{"is-on" if sgm == fill else ""}">{esc(sgm)}</i>' for sgm in segs)
                    + "</span>")
    elif re.match(r"^\s*date rows?\b", tok["after"]) and not vals:
        tail.append('<span class="mock-row__v"><span class="mock-line mock-line--w45" style="display:block;width:56px"></span></span>')
    if "jam" in marks and "current" not in marks and "tick" not in marks and not opts.get("val_chips"):
        cls.append("mock-row--jam")
        if not tail:
            tail.append('<span class="mock-dot mock-dot--jam" aria-hidden="true"></span>')
    if "ink" in marks and tail:
        tail[-1] = tail[-1].replace("mock-chip", "mock-chip mock-chip--ink", 1)
    t_cls = "mock-row__t"
    return (f'<div class="{" ".join(cls)}" style="--i:{i}">{n_html}{lead}'
            f'<span class="{t_cls}">{esc(head)}</span>{"".join(tail)}</div>')


def stub_rows(n: int, marked: list[int], chip_text: str | None, numbered: bool = True, start: int = 0,
              checkboxes: bool = False, strike_rows: dict | None = None) -> str:
    out = []
    widths = ["mock-line--w80", "mock-line--w60", "mock-line", "mock-line--w45", "mock-line--w80", "mock-line--w60", "mock-line", "mock-line--w45"]
    for k in range(n):
        idx = k + 1
        is_marked = idx in marked
        n_html = f'<span class="mock-row__n">{idx:02d}</span>' if numbered else ""
        lead = ""
        if checkboxes:
            lead = tick() if is_marked else '<span class="mock-ring" aria-hidden="true"></span>'
        body = f'<span class="mock-row__t"><span class="mock-line {widths[k % 8]}{" mock-line--dark" if is_marked else ""}" style="display:block;max-width:{78 if is_marked else 64}%"></span></span>'
        if strike_rows and idx in strike_rows:
            body = f'<span class="mock-row__t" style="text-decoration:line-through;color:var(--grey)">{esc(strike_rows[idx])}</span>'
        tail = ""
        if is_marked:
            if chip_text:
                tail += chip(chip_text, "mock-chip--jam")
            if not checkboxes:
                tail += tick()
        out.append(f'<div class="mock-row{"" if is_marked else " mock-row--muted"}" style="--i:{start + k}">{n_html}{lead}{body}{tail}</div>')
    return "".join(out)


def find_marked_rows(spec: str) -> list[int]:
    m = re.search(r"rows? \(?(\d{2})(?: and (\d{2}))?\)?", spec)
    if not m:
        m = re.search(r"\((\d{2}) and (\d{2})\)", spec)
    if not m:
        return []
    return [int(x) for x in m.groups() if x]


ROW_NOUN = r"(?:rows?|beats?|steps?|lines?|items?|entries|permissions|sources?|takes?|stages?)"


def find_row_count(spec: str) -> int:
    """'Three rows', 'five beats', '8 lines' → the intended row count."""
    m = re.search(r"\b(Eight|Five|Six|Seven|Four|Three|Two|eight|five|six|seven|four|three|two)\s+"
                  r"(?:numbered |short |small |stacked |note |stage |source |grey |rows? with |section )?" + ROW_NOUN + r"\b", spec)
    if m:
        return wordnum(m.group(1))
    m = re.search(r"\b(\d)\s+" + ROW_NOUN + r"\b", spec)
    return int(m.group(1)) if m else 0


def paren_enum(spec: str) -> list[tuple[str, str]]:
    """A parenthesised enumeration of numbered steps —
    '(01 Problem, 02 Discovery, 03 Demo, 04 Payoff, 05 Call to action)' —
    which Lance-style specs use instead of quoting every row. Returns
    [(number, label), …] when the parenthesis holds three or more of them."""
    for m in re.finditer(r"\(([^()]{12,220})\)", spec):
        parts = [p.strip() for p in m.group(1).split(",") if p.strip()]
        pairs = []
        for p in parts:
            mm = re.match(r"^(\d{2})\s+(.{2,40})$", p)
            if not mm:
                pairs = []
                break
            pairs.append((mm.group(1), mm.group(2).strip()))
        if len(pairs) >= 3:
            return pairs
    return []


def paren_tag_list(spec: str) -> list[str]:
    """The quoted tag run that follows such a list: ('0–3s', '3–8s', …)."""
    m = re.search(r"\(\s*('(?:[^']|'\w)*'(?:\s*,\s*'(?:[^']|'\w)*')*)\s*(?:,\s*…)?\s*\)", spec)
    if not m:
        return []
    return [t.strip().strip("'") for t in re.findall(r"'([^']*)'", m.group(1))]


def extend_tags(tags: list[str], n: int) -> list[str]:
    """'0–3s', '3–8s', …  →  continue the run to n tags (the spec's own '…').
    Only extends duration ranges; anything else is returned untouched."""
    if len(tags) >= n or len(tags) < 2:
        return tags
    rng = re.compile(r"^(\d+)\s*[–-]\s*(\d+)\s*s$")
    ms = [rng.match(t) for t in tags]
    if not all(ms):
        return tags
    a, b = int(ms[-1].group(1)), int(ms[-1].group(2))
    step = b - a
    out = list(tags)
    while len(out) < n:
        a, b = b, b + step
        out.append(f"{a}–{b}s")
    return out


def dims(spec: str, default=(400, 300)) -> tuple[int, int]:
    m = re.search(r"(\d{3})×(\d{3})", spec)
    return (int(m.group(1)), int(m.group(2))) if m else default


