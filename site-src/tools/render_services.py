    if "progress row" in s or ("timeline" in s and "tick" in s) or ("small timeline" in s):
        return f'<div class="page-panel"><div class="mock-stage">{steps_card(spec, toks, w)}</div></div>'

    if "grid" in s and "×" in spec:
        return f'<div class="page-panel"><div class="mock-stage">{grid_card(spec, toks, w)}</div></div>'

    if "seals" in s:
        return f'<div class="page-panel"><div class="mock-stage">{seals_card(spec, toks, w)}</div></div>'

