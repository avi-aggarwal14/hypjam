def render_page(data: dict, i: int, item: dict) -> str:
    p = f"items.{i}"
    meta = [
        ("title", c(p + ".title")),
        ("description", c(p + ".description")),
        ("nav", "light"), ("nav-fill", "bg-white"), ("body-class", f"svc svc--{item['slug']}"),
        ("cta-h2", c(p + ".cta.h2")), ("cta-p", c(p + ".cta.p")),
        ("cta-label", c(p + ".cta.button.label")), ("cta-href", c(p + ".cta.button.href")),
    ]
    out = [head(meta), f'<main class="page svc svc--{item["slug"]}" data-theme="light">']
    # hero
    out.append('<section class="page-section page-section--hero-split"><div class="page-hero page-hero--split"><div class="page-hero__copy">')
    out.append(f'<p class="page-hero__crumb"><a href="/services">{{{{content:nav.left.0.label|Services}}}}</a><span aria-hidden="true">/</span>'
               f'<span class="page-hero__crumb-current">{c(p + ".eyebrow")}</span></p>')
    out.append(f'<h1 class="page-hero__title">{c(p + ".h1")}</h1>')
    out.append(f'<p class="page-hero__intro">{c(p + ".intro")}</p>')
    out.append(f'<div class="page-hero__cta">{btn(c("cta_button.label"), c("cta_button.href"))}</div>')
    out.append('</div><div class="page-hero__visual" aria-hidden="true">')
    out.append(build_mock(item["hero_visual"], hero=True))
    out.append("</div></div>")
    out.append('<div class="page-hero__platforms">{{include:partials/platforms-row.html}}</div></section>')
    # statement + facts
    out.append('<section class="page-section page-section--stats page-stats">')
    out.append(f'<h2 class="page-h2 page-stats__h2">{c(p + ".statement")}</h2><div class="page-stats__row">')
    for k, fact in enumerate(item["facts"]):
        fp = f"{p}.facts.{k}"
        num = str(fact["num"]).strip()
        if re.fullmatch(r"\d+", num):
            num_html = f'<span data-count="{int(num)}">{c(fp + ".num")}</span>'
        else:
            num_html = f'<span>{c(fp + ".num")}</span>'
        out.append(f'<div class="page-stat"><p class="page-stat__num">{num_html}<span>{c(fp + ".suffix")}</span></p>'
                   f'<p class="page-stat__label">{c(fp + ".label")}</p></div>')
    out.append("</div></section>")
    # features
    out.append('<section class="page-section page-section--features"><div class="page-features">')
    for k, feat in enumerate(item["features"]):
        fp = f"{p}.features.{k}"
        flip = " page-feature--flip" if k % 2 == 1 else ""
        out.append(f'<div class="page-feature{flip}"><div class="page-feature__text">')
        out.append(f'<h2 class="page-h2 page-feature__h2">{c(fp + ".title")}</h2><p class="page-feature__p">{c(fp + ".body")}</p>')
        out.append('<div class="page-feature__bullets">')
