def render_blog() -> None:
    blog = load("blog")
    agency = load("agency")
    arts = blog["articles"]
    link_map = blog.get("link_map", {})
    ap = blog["article_page"]

    # ---- index -----------------------------------------------------------
    filters = blog["filters"]
    pills = []
    for i, f in enumerate(filters):
        key = "all" if i == 0 else f
        pressed = "true" if i == 0 else "false"
        pills.append(f'<button type="button" class="blog-filter" data-filter="{esc(key)}" aria-pressed="{pressed}">{T(f"blog.filters.{i}")}</button>')

    cards = []
    for i, a in enumerate(arts):
        cards.append(
            f'<a class="blog-card" href="{esc(a["href"])}" data-cat="{esc(a["category"])}">'
            f'<span class="blog-card-art" aria-hidden="true">{motif(a.get("art", ""))}</span>'
            f'<span class="blog-card-cap"><b class="blog-card-date">{T(f"blog.articles.{i}.date_label")}</b> '
            f'<span class="blog-card-title">{T(f"blog.articles.{i}.title")}</span></span></a>'
        )

    index_ld = jsonld({
        "@context": "https://schema.org",
        "@type": "Blog",
        "name": blog["hero"]["h1"],
        "url": BASE_URL + blog["meta"]["path"],
        "description": blog["meta"]["description"],
        "publisher": {"@type": "Organization", "name": "hypjam", "url": BASE_URL},
        "blogPost": [{"@type": "BlogPosting", "headline": a["title"], "url": BASE_URL + a["href"],
                      "datePublished": a["date"], "author": {"@type": "Person", "name": agency["founder"]["name"]}} for a in arts],
    })

    index_page = "\n".join([
        meta_block(blog["meta"]["title"], blog["meta"]["description"], "dark", "bg-transparent", "page-blog", index_ld),
        GEN % "blog",
        "{{include:partials/head.html}}",
        "{{include:partials/nav.html}}",
        '<main class="blog" data-theme="light">',
        '  <section class="blog-hero" data-nav="dark" data-nav-fill="bg-transparent">',
        '    <img class="blog-hero-bg" src="/assets/video/hero-poster.jpg" alt="" width="1280" height="720" decoding="async" fetchpriority="high">',
        '    <div class="blog-hero-shade" aria-hidden="true"></div>',
        '    <div class="blog-hero-body">',
        f'      <img class="blog-hero-mark" src="{esc(blog["hero"]["mark"])}" alt="" width="52" height="52">',
        f'      <h1 class="blog-hero-h1">{T("blog.hero.h1")}</h1>',
        f'      <p class="blog-hero-sub">{T("blog.hero.sub")}</p>',
        "    </div>",
        "  </section>",
        '  <section class="blog-list section--sand-m" data-nav="light" data-nav-fill="bg-sand-m">',
        '    <div class="blog-filters" role="group" aria-label="Filter articles">',
        "      " + "\n      ".join(pills),
        "    </div>",
        '    <div class="blog-grid">',
        "      " + "\n      ".join(cards),
        "    </div>",
        "  </section>",
        "</main>",
        "<script>(function(){var b=document.querySelectorAll('.blog-filter'),c=document.querySelectorAll('.blog-card');"
        "for(var i=0;i<b.length;i++){b[i].addEventListener('click',function(){var f=this.getAttribute('data-filter');"
        "for(var j=0;j<b.length;j++)b[j].setAttribute('aria-pressed',b[j]===this?'true':'false');"
        "for(var k=0;k<c.length;k++)c[k].hidden=!(f==='all'||c[k].getAttribute('data-cat')===f);"
        "if(window.ScrollTrigger&&ScrollTrigger.refresh)ScrollTrigger.refresh();});}})();</script>",
        "{{include:partials/footer.html}}",
        "{{include:partials/scripts.html}}",
        "",
    ])
    write("blog/index.html", index_page)

    # ---- articles --------------------------------------------------------
    for i, a in enumerate(arts):
        src_path = Path(a["body"])
        if not src_path.is_file():
            print(f"  ! missing article body: {src_path}", file=sys.stderr)
            continue
        body_html, toc = md.md_to_html(src_path.read_text(encoding="utf-8"), link_map=link_map, lede=True)
