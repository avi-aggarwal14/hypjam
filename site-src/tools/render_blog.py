            "  </article>",
            '  <section class="blog-more">',
            '    <div class="blog-more-head">',
            '      <h2 class="blog-more-h2">More guides</h2>',
            f'      <a class="arrow-link" href="{esc(ap["back"]["href"])}">{T("blog.article_page.back.label")} {ARROW}</a>',
            "    </div>",
            '    <div class="blog-more-grid">',
            "      " + "\n      ".join(more),
            "    </div>",
            "  </section>",
            '  <section class="blog-cta section--sand-s">',
            f'    <h2 class="blog-cta-h2 t-h2">{T("blog.article_page.cta.h2")}</h2>',
