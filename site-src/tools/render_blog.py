"""render_blog.py — stamps out the content-driven inner pages from content/*.json.

Writes (all under src/pages/):
  blog/index.html            the blog index (content/blog.json)         → /blog
  blog/<slug>.html ×8        the article template, one per article      → /blog/<slug>
  privacy.html, terms.html   the legal template (content/legal.json)    → /privacy, /terms
  process.html               the documentation-style page (process.json)→ /process
  faq.html                   two accordion groups (faq.json)            → /faq
  agency.html                the agency page (agency.json)              → /agency
  join.html                  the creator roster page (join.json)        → /join

Why one renderer for all of them: every one of these pages is a loop over
JSON arrays (eight articles, ten legal sections, fourteen FAQ items, three
weeks × four topics × blocks …). Hand-writing {{content:…}} tokens for each
index is brittle; generating them keeps content/*.json the single source of
truth (build.py runs this before it expands pages, so a JSON edit flows
through on the next build). Text nodes are still emitted as
{{content:file.path}} tokens wherever the value is a plain string; only
derived output (rendered Markdown, related-article picks, JSON-LD, escaped
attribute values) is written literally.

Markdown → HTML is tools/md.py. Standard library only. Idempotent.
"""

