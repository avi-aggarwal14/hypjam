            f'        <div class="blog-rail-item"><dt class="blog-rail-k">In this guide</dt><dd class="blog-rail-v"><ol class="blog-rail-toc">{toc_html}</ol></dd></div>',
            "      </dl>",
            "    </aside>",
            '    <div class="blog-col">',
            '      <div class="blog-prose">',
