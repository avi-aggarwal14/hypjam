        h2s = [(sid, txt) for sid, txt, lvl in toc if lvl == 2]

        # related: same category first, then editorial order, never itself
        same = [b for b in arts if b is not a and b["category"] == a["category"]]
        rest = [b for b in arts if b is not a and b["category"] != a["category"]]
        related = (same + rest)[: int(ap.get("related_count", 3))]

