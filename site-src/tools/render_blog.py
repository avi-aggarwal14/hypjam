def render_legal() -> None:
    legal = load("legal")
    related = legal.get("related", [])
    for key, pg in legal["pages"].items():
        src_path = Path(pg["source"])
        if not src_path.is_file():
            print(f"  ! missing legal source: {src_path}", file=sys.stderr)
            continue
        rendered, _toc = md.md_to_html(src_path.read_text(encoding="utf-8"), strip_last_updated=True)
        intro, secs = md.sections(rendered)

        rel_links = []
        for r in related:
            cur = ' aria-current="page"' if r["href"] == pg["path"] else ""
            rel_links.append(f'<a class="legal-rel-a" href="{esc(r["href"])}"{cur}>{html.escape(r["label"], quote=False)}</a>')

        sec_html = []
        for n, (head, body) in enumerate(secs, start=1):
            sec_html.append(
                '      <section class="legal-sec">\n'
                f'        <span class="legal-num" aria-hidden="true">{n}</span>\n'
                '        <div class="legal-sec-body">\n'
                f"          {head}\n{body}\n"
                "        </div>\n"
                "      </section>"
            )

        ld = jsonld({
            "@context": "https://schema.org",
            "@type": "WebPage",
            "name": pg["h1"],
            "url": BASE_URL + pg["path"],
            "description": pg["description"],
            "dateModified": pg["last_updated"],
            "inLanguage": "en-GB",
            "publisher": {"@type": "Organization", "name": "hypjam", "url": BASE_URL},
        })

        page = "\n".join([
            meta_block(pg["title"], pg["description"], "light", "bg-sand-s", "page-legal", ld),
            GEN % "legal",
            "{{include:partials/head.html}}",
            "{{include:partials/nav.html}}",
            '<main class="legal" data-theme="sand">',
            '  <div class="legal-wrap">',
            f'    <a class="legal-back" href="/">{ARROW_LEFT}Back to home</a>',
            f'    <p class="legal-eyebrow t-eyebrow">{T(f"legal.pages.{key}.eyebrow")}</p>',
            f'    <h1 class="legal-h1">{T(f"legal.pages.{key}.h1")}</h1>',
            f'    <p class="legal-updated">Last updated {T(f"legal.pages.{key}.last_updated")}</p>',
            f'    <nav class="legal-related" aria-label="Legal pages">{" ".join(rel_links)}</nav>',
            f'    <div class="legal-intro">\n{intro}\n    </div>',
            '    <div class="legal-secs">',
            "\n".join(sec_html),
            "    </div>",
            "  </div>",
            "</main>",
            "{{include:partials/footer.html}}",
            "{{include:partials/scripts.html}}",
            "",
        ])
        write(f"{key}.html", page)


