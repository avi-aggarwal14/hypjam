# ---------------------------------------------------------------------------
# spec strings: the quoted spans are the mock's copy, kept in the JSON
# ---------------------------------------------------------------------------

# An opening/closing quote never touches a letter or digit, so a possessive
# ("the card's hook line") does not swallow the span that follows it.
_QUOTED = re.compile(r"(?<![A-Za-z0-9])'([^']*)'(?![A-Za-z0-9])")


def quoted(spec: str) -> list[str]:
    """The single-quoted spans of a mock spec, in order — the mock's copy."""
    return [s.strip() for s in _QUOTED.findall(spec or "") if s.strip()]


def q(spans: list[str], i: int, fallback: str = "") -> str:
    return esc(spans[i]) if 0 <= i < len(spans) else esc(fallback)


