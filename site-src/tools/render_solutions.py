def main() -> int:
    data = json.loads(CONTENT.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = []

    target = OUT_DIR / "index.html"
    target.write_text(render_index(data), encoding="utf-8")
    written.append(target)

    for i, p in enumerate(data["pages"]):
        html = render_brand(data, i, p) if p.get("group") == "brand" else render_goal(data, i, p)
        target = OUT_DIR / f"{p['slug']}.html"
        target.write_text(html, encoding="utf-8")
        written.append(target)

    keep = {t.name for t in written}
    for old in OUT_DIR.glob("*.html"):
        if old.name not in keep and GENERATED in old.read_text(encoding="utf-8", errors="ignore"):
            old.unlink()
            print("removed", old.relative_to(ROOT))

    for t in written:
        print("wrote", t.relative_to(ROOT))
    if MISSING_ICONS:
        print("render_solutions: no drawing for icon(s):", ", ".join(sorted(MISSING_ICONS)))
    if MISSING_MOCKS:
        print("render_solutions: no builder for mock(s):", ", ".join(sorted(MISSING_MOCKS)))
    if MISSING_ROOMS:
        print("render_solutions: hq.svg room group(s) missing, used the footer drawing:",
              ", ".join(str(r) for r in sorted(MISSING_ROOMS)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
