def rrect(x, y, w, h, r=6, extra=""):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}"{extra}/>'


def phone(x, y, w, h, r=10):
    return (rrect(x, y, w, h, r) +
            f'<path d="M{x + w / 2 - 7} {y + 6}h14"/>')


def play(cx, cy, s=14):
    return f'<path d="M{cx - s * .45} {cy - s * .6}l{s * 1.05} {s * .6}l{-s * 1.05} {s * .6}z"/>'


def doc(x, y, w, h, lines=3, fold=True):
    out = (f'<path d="M{x} {y}h{w - 14}l14 14v{h - 14}H{x}z"/>' if fold
           else rrect(x, y, w, h, 3))
    if fold:
        out += f'<path d="M{x + w - 14} {y}v14h14"/>'
    for i in range(lines):
        out += f'<path d="M{x + 12} {y + 30 + i * 16}h{w - 30}"/>'
    return out


def envelope(x, y, w, h):
    return rrect(x, y, w, h, 5) + f'<path d="M{x + 2} {y + 5}l{w / 2 - 2} {h * .55}l{w / 2 - 2} {-h * .55}"/>'


def clock(cx, cy, r):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}"/><path d="M{cx} {cy - r * .55}V{cy}h{r * .5}"/>'


def tick_circle(cx, cy, r):
    return (f'<circle cx="{cx}" cy="{cy}" r="{r}"/>'
            f'<path d="M{cx - r * .45} {cy}l{r * .35} {r * .38}l{r * .62} {-r * .72}"/>')


def arrow(x1, y1, x2, y2, head=7):
    import math
    a = math.atan2(y2 - y1, x2 - x1)
    p1 = (x2 - head * math.cos(a - .5), y2 - head * math.sin(a - .5))
    p2 = (x2 - head * math.cos(a + .5), y2 - head * math.sin(a + .5))
    return (f'<path d="M{x1:.0f} {y1:.0f}L{x2:.0f} {y2:.0f}"/>'
            f'<path d="M{p1[0]:.1f} {p1[1]:.1f}L{x2:.0f} {y2:.0f}L{p2[0]:.1f} {p2[1]:.1f}"/>')


def textlines(x, y, w, n, gap=12):
    return "".join(f'<path d="M{x} {y + i * gap}h{w if i < n - 1 else w * .62:.0f}"/>' for i in range(n))


def note(cx, cy, s=1.0):
    return (f'<path d="M{cx} {cy}v{-26 * s}l{16 * s} {-5 * s}v{26 * s}"/>'
            f'<ellipse cx="{cx - 5 * s}" cy="{cy + 4 * s}" rx="{6 * s}" ry="{4.5 * s}"/>'
            f'<ellipse cx="{cx + 11 * s}" cy="{cy}" rx="{6 * s}" ry="{4.5 * s}"/>')


def clapper(x, y, w, h):
    return (rrect(x, y + 12, w, h - 12, 3) +
            f'<path d="M{x} {y + 12}l{4} {-9}l{w * .28:.0f} {-3}l{-4} {9}z"/>'
            f'<path d="M{x + w * .28:.0f} {y + 12}l{4} {-9}l{w * .28:.0f} {-3}l{-4} {9}z"/>'
            f'<path d="M{x + w * .56:.0f} {y + 12}l{4} {-9}l{w * .28:.0f} {-3}l{-4} {9}z"/>')


def hand(x, y):
    """A simple line-drawn hand holding something, anchored bottom-left."""
