_ATTR_DROP = re.compile(r'\s(?:stroke|stroke-width|fill|stroke-linecap|stroke-linejoin)="[^"]*"')
_GROUP = re.compile(r"<g\b|</g>")


def room_group(svg: str, gid: str) -> str | None:
    start = svg.find(f'<g id="{gid}">')
    if start < 0:
        return None
    depth, pos = 0, start
    while True:
        m = _GROUP.search(svg, pos)
        if not m:
            return None
        if m.group(0) == "</g>":
            depth -= 1
            pos = m.end()
            if depth == 0:
                break
        else:
            depth += 1
            pos = m.end()
    frag = svg[start:pos]
    frag = frag[frag.index(">") + 1:frag.rindex("</g>")]     # inner markup only
    return _ATTR_DROP.sub("", frag)


_ROOM_CACHE: dict[int, str] = {}
MISSING_ROOMS: set[int] = set()


def room_svg(room: int, alt: str) -> str:
    """An inline SVG cropped to one room of src/drawing/hq.svg, restyled to a
    1px grey stroke. Falls back to the small footer drawing if the group is
    not there yet (the drawing agent may still be writing it)."""
    if room not in _ROOM_CACHE:
        body = None
        if DRAWING.exists() and room in ROOMS:
            try:
                body = room_group(DRAWING.read_text(encoding="utf-8", errors="ignore"), ROOMS[room][0])
            except Exception:
                body = None
        if not body:
            MISSING_ROOMS.add(room)
            _ROOM_CACHE[room] = ""
        else:
            _, x, y, w, h = ROOMS[room]
            pad = int(w * 0.03)
            vb = f"{x - pad} {y - pad} {w + pad * 2} {h + pad * 2}"
            _ROOM_CACHE[room] = (
                f'<svg class="sol-room" viewBox="{vb}" role="img" aria-label="{alt}" '
                f'preserveAspectRatio="xMidYMid meet">'
                f'<g fill="none" stroke="currentColor" stroke-width="1" stroke-linecap="round" '
                f'stroke-linejoin="round">{body}</g></svg>')
    art = _ROOM_CACHE[room]
    if art:
        return art
    return (f'<img class="sol-room" src="/assets/img/hq-footer.svg" alt="{alt}" '
            f'width="420" height="180" loading="lazy" decoding="async">')


